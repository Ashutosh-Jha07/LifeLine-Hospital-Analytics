create DATABASE lifeline_hospital_analytics;
USE lifeline_hospital_analytics;
CREATE TABLE healthcare_data (
    Patient_ID INT,
    Admit_Date VARCHAR(20),
    Discharge_Date VARCHAR(20),
    Diagnosis VARCHAR(100),
    Bed_Occupancy VARCHAR(30),
    Test VARCHAR(100),
    Doctor_Name VARCHAR(100),
    Followup_Date VARCHAR(20),
    Feedback VARCHAR(30),
    Billing_Amount VARCHAR(20),
    Health_Insurance_Amount VARCHAR(20),
    Total_Amount_Payable VARCHAR(20)
);

#Q1: How many patients were admitted to the hospital?
CREATE VIEW total_patients AS
SELECT COUNT(*) AS Total_Patients
FROM healthcare_data;

# Result
SELECT * FROM total_patients;

 # Q2: What is the total hospital revenue?
 CREATE VIEW total_hospital_revenue AS
SELECT
    SUM(Billing_Amount_Clean) AS Total_Hospital_Revenue
FROM healthcare_data;

#Result
SELECT * FROM total_hospital_revenue;

# Q3: What is the average billing amount per patient?
CREATE VIEW average_billing_amount AS
SELECT
    ROUND(AVG(Billing_Amount_Clean),2) AS Average_Billing_Amount
FROM healthcare_data;

#Result
SELECT * FROM vw_average_billing_amount;

# Q4: What is the average length of stay of patients?
CREATE VIEW average_length_of_stay AS
SELECT
    ROUND(AVG(Length_of_Stay), 2) AS Average_Length_of_Stay
FROM healthcare_data;

#Result
SELECT * FROM average_length_of_stay;

# Q5: How many unique doctors treated patients?
CREATE VIEW total_doctors AS
SELECT
    COUNT(DISTINCT Doctor_Name) AS Total_Doctors
FROM healthcare_data;

#Result
SELECT * FROM vw_total_doctors;

# Q6: How many different diagnoses were treated?
CREATE VIEW total_diagnoses AS
SELECT
    COUNT(DISTINCT Diagnosis) AS Total_Diagnoses
FROM healthcare_data;

# Result
SELECT * FROM total_diagnoses;

# Q7: How many patients had a follow-up appointment versus no follow-up?
CREATE VIEW followup_status AS
SELECT
    CASE
        WHEN Followup_Date_Clean IS NULL THEN 'No Follow-up'
        ELSE 'Follow-up Scheduled'
    END AS Followup_Status,
    COUNT(*) AS Total_Patients
FROM healthcare_data
GROUP BY Followup_Status;

# Result
SELECT * FROM followup_status;

# Q8: Which are the Top 10 doctors by number of patients treated?
CREATE VIEW top10_doctors_by_patients AS
SELECT
    Doctor_Name,
    COUNT(*) AS Total_Patients
FROM healthcare_data
GROUP BY Doctor_Name
ORDER BY Total_Patients DESC
LIMIT 10;

# Result
SELECT * FROM top10_doctors_by_patients;
   
