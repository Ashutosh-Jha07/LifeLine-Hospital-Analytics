# Q15: Rank doctors based on total revenue generated.
CREATE VIEW doctor_revenue_rank AS
SELECT
    Doctor_Name,
    SUM(Billing_Amount_Clean) AS Total_Revenue,
    RANK() OVER (ORDER BY SUM(Billing_Amount_Clean) DESC) AS Revenue_Rank
FROM healthcare_data
GROUP BY Doctor_Name;

#Result
SELECT * FROM doctor_revenue_rank;

# Q16: Find the Top 10 highest billing patients.
CREATE VIEW top10_highest_billing_patients AS
SELECT
    Patient_ID,
    Doctor_Name,
    Diagnosis,
    Billing_Amount_Clean
FROM healthcare_data
ORDER BY Billing_Amount_Clean DESC
LIMIT 10;

#Result
SELECT * FROM top10_highest_billing_patients;

# Q17: Calculate monthly hospital revenue
CREATE VIEW monthly_revenue AS
SELECT
    DATE_FORMAT(Admit_Date_Clean,'%Y-%m') AS Month,
    SUM(Billing_Amount_Clean) AS Total_Revenue
FROM healthcare_data
GROUP BY Month
ORDER BY Month;

#Result
SELECT * FROM monthly_revenue;

# Q18: Calculate monthly patient admissions.
CREATE VIEW monthly_admissions AS
SELECT
    DATE_FORMAT(Admit_Date_Clean,'%Y-%m') AS Month,
    COUNT(*) AS Total_Admissions
FROM healthcare_data
GROUP BY Month
ORDER BY Month;

#Result
SELECT * FROM monthly_admissions;

# Q19: Calculate the insurance coverage percentage for each patient.
CREATE VIEW insurance_coverage_percentage AS
SELECT
    Patient_ID,
    Billing_Amount_Clean,
    Health_Insurance_Amount_Clean,
    ROUND((Health_Insurance_Amount_Clean / Billing_Amount_Clean) * 100,2) AS Insurance_Coverage_Percentage
FROM healthcare_data;

#Result
SELECT * FROM insurance_coverage_percentage;

# Q20: Which month generated the highest hospital revenue?
CREATE VIEW highest_revenue_month AS
SELECT
    DATE_FORMAT(Admit_Date_Clean,'%Y-%m') AS Month,
    SUM(Billing_Amount_Clean) AS Total_Revenue
FROM healthcare_data
GROUP BY Month
ORDER BY Total_Revenue DESC
LIMIT 1;

#Result
SELECT * FROM highest_revenue_month;

















